#!/usr/bin/env node
/* ===========================================================
   Emits the README's chronology table from site/data/mechanisms.js.

   The point is that there is exactly one place a date lives. The
   timeline, the dossiers, Act 5's table and the README all read from
   that file — so a corrected date propagates instead of leaving three
   stale copies behind, which is the specific failure this assignment
   is designed to punish.

   Usage:
     node tools/gen-readme-table.js            # print to stdout
     node tools/gen-readme-table.js --write    # splice into README.md
                                               # between the marker comments
   =========================================================== */
'use strict';
var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
global.window = {};
require(path.join(ROOT, 'site/data/mechanisms.js'));

var M = global.window.MECHANISMS;
var CTX = global.window.CONTEXT_MARKER;
var LANES = global.window.LANES;

var START = '<!-- CHRONOLOGY-TABLE:START -->';
var END = '<!-- CHRONOLOGY-TABLE:END -->';

/* The verified field is dossier HTML. Markdown needs it as prose, and a stray
   <strong> in a table cell is the kind of thing nobody notices until it ships. */
function toMd(s) {
  return String(s)
    .replace(/<strong>(.*?)<\/strong>/g, '**$1**')
    .replace(/<em>(.*?)<\/em>/g, '*$1*')
    .replace(/<code>(.*?)<\/code>/g, '`$1`')
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/\|/g, '\\|')     // a literal pipe would break the row
    .replace(/\s+/g, ' ')
    .trim();
}

function srcCell(m) {
  var label = m.src === 'reddit' ? 'r/LocalLLaMA post'
            : m.src === 'github' ? 'GitHub PR'
            : 'arXiv:' + m.src;
  return '[' + label + '](' + m.url + ')';
}

function build() {
  var rows = M.concat([CTX]);
  var out = [];

  out.push('| # | Date | Mechanism | Lane | Primary source | Tier | How the date was checked |');
  out.push('|---|------|-----------|------|----------------|------|--------------------------|');

  rows.forEach(function (m) {
    var isCtx = (m === CTX);
    out.push('| ' + [
      isCtx ? '—' : m.n,
      m.date,
      '**' + toMd(m.name) + '**',
      isCtx ? '*context*' : LANES[m.lane].short,
      srcCell(m) + (m.v1 ? '<br>`v1 ' + m.v1 + '`' : ''),
      m.tier,
      toMd(m.verified)
    ].join(' | ') + ' |');
  });

  var arx = rows.filter(function (m) { return !!m.v1; });
  var ids = {};
  arx.forEach(function (m) { ids[m.src] = 1; });
  var t = {A: 0, B: 0, C: 0};
  rows.forEach(function (m) { t[m.tier]++; });

  out.push('');
  out.push('**' + rows.length + ' rows** — 21 mechanisms plus one model quoted for its numbers. ' +
    arx.length + ' dated from an arXiv **v1** submission record (' + Object.keys(ids).length +
    ' distinct papers; two rows share *Attention Is All You Need*), ' + (rows.length - arx.length) +
    ' from sources with no paper at all. Evidence tiers: **A ' + t.A + ' / B ' + t.B +
    ' / C ' + t.C + '**.');
  out.push('');
  out.push('*Generated by `tools/gen-readme-table.js` from `site/data/mechanisms.js`. ' +
    'Do not edit by hand — rerun the generator.*');

  return out.join('\n');
}

var table = build();

if (process.argv.indexOf('--write') >= 0) {
  var readme = path.join(ROOT, 'README.md');
  if (!fs.existsSync(readme)) {
    console.error('README.md does not exist yet — run without --write and paste, or create it first.');
    process.exit(1);
  }
  var src = fs.readFileSync(readme, 'utf8');
  var a = src.indexOf(START), b = src.indexOf(END);
  if (a < 0 || b < 0) {
    console.error('Markers not found in README.md. Add these two lines where the table belongs:\n' +
      '  ' + START + '\n  ' + END);
    process.exit(1);
  }
  fs.writeFileSync(readme,
    src.slice(0, a + START.length) + '\n' + table + '\n' + src.slice(b));
  console.error('README.md updated (' + (M.length + 1) + ' rows).');
} else {
  process.stdout.write(table + '\n');
}
